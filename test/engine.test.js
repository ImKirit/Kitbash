test('hash mismatch is refused before the game folder is touched', async () => {
  // package differs from the catalog
  let s = h.scene({ foreign: true });
  let before = h.snapshot(s.gameDir);
  fs.appendFileSync(s.files.modZips.alpha, 'tampered');
  await assert.rejects(s.engine.prepare(s.plan, s.files), (e) => e.code === 'hash-mismatch' && e.what === 'alpha');
  assert.deepEqual(h.snapshot(s.gameDir), before);
  assert.equal(s.engine.pendingJournals().length, 0);
  h.cleanupDir(s.root);

  // loader differs from the catalog
  s = h.scene({ foreign: true });
  before = h.snapshot(s.gameDir);
  fs.appendFileSync(s.files.loaderZip, 'x');
  await assert.rejects(s.engine.prepare(s.plan, s.files), (e) => e.code === 'hash-mismatch');
  assert.deepEqual(h.snapshot(s.gameDir), before);
  h.cleanupDir(s.root);

  // package hash is right, but a file inside is not what the catalog lists
  s = h.scene();
  before = h.snapshot(s.gameDir);
  const evil = writeZip([
    { name: 'BepInEx/plugins/Alpha/Alpha.dll', data: 'swapped code' },
    { name: 'BepInEx/plugins/Alpha/extra.dat', data: 'alpha extra' },
  ]);
  fs.writeFileSync(s.files.modZips.alpha, evil);
  s.plan.mods[0] = { ...s.plan.mods[0], package: { ...s.plan.mods[0].package, sha256: sha256(evil), size: evil.length } };
  await assert.rejects(s.engine.prepare(s.plan, s.files), (e) => e.code === 'hash-mismatch');
  assert.deepEqual(h.snapshot(s.gameDir), before);
  h.cleanupDir(s.root);
});

test('zip path traversal and files outside the mod folders are refused', async () => {
  const hostile = [
    '../evil.dll',
    'BepInEx/plugins/../../evil.dll',
    '/abs/evil.dll',
    'C:/Windows/evil.dll',
    'BepInEx\\plugins\\evil.dll',
    'BepInEx/plugins/Alpha/nul',
    'BepInEx/plugins/Alpha/trailing./x.dll',
  ];
  for (const name of hostile) {
    const s = h.scene({ foreign: true });
    const before = h.snapshot(s.gameDir);
    const outside = h.snapshot(s.root);
    const zip = writeZip([{ name, data: 'evil' }], { raw: true });
    fs.writeFileSync(s.files.modZips.alpha, zip);
    s.plan.mods[0] = {
      ...s.plan.mods[0],
      package: { ...s.plan.mods[0].package, sha256: sha256(zip), size: zip.length },
      files: [{ path: name, size: 4, sha256: sha256(Buffer.from('evil')) }],
    };
    await assert.rejects(s.engine.prepare(s.plan, s.files), (e) => e.code === 'EZIP', 'accepted ' + name);
    assert.deepEqual(h.snapshot(s.gameDir), before, name);
    // nothing appeared next to the game folder either
    const after = h.snapshot(s.root);
    delete after['alpha.zip']; delete outside['alpha.zip'];
    assert.deepEqual(after, outside, name);
    h.cleanupDir(s.root);
  }

  // a well formed name that points at a game file
  for (const name of ['Fake_Data/Managed/Assembly-CSharp.dll', 'Fake.exe', 'BepInEx/core/BepInEx.dll', 'winhttp.dll']) {
    const s = h.scene();
    const before = h.snapshot(s.gameDir);
    const zip = writeZip([{ name, data: 'evil' }]);
    fs.writeFileSync(s.files.modZips.alpha, zip);
    s.plan.mods[0] = {
      ...s.plan.mods[0],
      package: { ...s.plan.mods[0].package, sha256: sha256(zip), size: zip.length },
      files: [{ path: name, size: 4, sha256: sha256(Buffer.from('evil')) }],
    };
    await assert.rejects(s.engine.prepare(s.plan, s.files), (e) => e.code === 'package-layout', 'accepted ' + name);
    assert.deepEqual(h.snapshot(s.gameDir), before, name);
    h.cleanupDir(s.root);
  }

  // a file in the package that the catalog does not list
  const s = h.scene();
  const zip = writeZip([
    { name: 'BepInEx/plugins/Alpha/Alpha.dll', data: 'alpha code' },
    { name: 'BepInEx/plugins/Alpha/extra.dat', data: 'alpha extra' },
    { name: 'BepInEx/plugins/Alpha/stowaway.dll', data: 'not listed' },
  ]);
  fs.writeFileSync(s.files.modZips.alpha, zip);
  s.plan.mods[0] = { ...s.plan.mods[0], package: { ...s.plan.mods[0].package, sha256: sha256(zip), size: zip.length } };
  await assert.rejects(s.engine.prepare(s.plan, s.files), (e) => e.code === 'package-layout');
  h.cleanupDir(s.root);
});

