test('mod data survives: saved after the game, put back on the next launch, deletions are mirrored', async () => {
  const s = h.scene({ foreign: true });
  const before = h.snapshot(s.gameDir);

  // first session: nothing in the store yet
  let journal = await s.engine.prepare(s.plan, s.files);
  assert.ok(!exists(path.join(s.gameDir, 'BepInEx/config/dev.test.alpha.cfg')));
  s.engine.mark(journal, 'launched');
  playGame(s.gameDir, 1);
  s.engine.mark(journal, 'exited');
  let result = s.engine.finish(journal);
  assert.deepEqual(result.saved.map((x) => x.id), ['alpha', 'beta']);
  assert.deepEqual(h.snapshot(s.gameDir), before);

  const alphaStore = path.join(s.dataDir, 'store/fakegame/alpha/data');
  assert.equal(fs.readFileSync(path.join(alphaStore, 'BepInEx/config/dev.test.alpha.cfg'), 'utf8'), 'consent = yes\nrun = 1\n');
  assert.deepEqual(fs.readFileSync(path.join(alphaStore, 'BepInEx/config/Alpha/76561190000000000/library.bin')), Buffer.alloc(3000, 1));
  assert.ok(s.engine.storeInfo('fakegame', 'alpha').exists);
  // data of one mod never lands in the store of another, loader files are not kept
  assert.ok(!exists(path.join(alphaStore, 'BepInEx/config/dev.test.beta.cfg')));
  assert.ok(!exists(path.join(alphaStore, 'BepInEx/config/BepInEx.cfg')));

  // second session: only alpha selected, its data is back before the game starts
  const planA = { ...s.plan, mods: [s.plan.mods[0]] };
  journal = await s.engine.prepare(planA, s.files);
  assert.equal(fs.readFileSync(path.join(s.gameDir, 'BepInEx/config/dev.test.alpha.cfg'), 'utf8'), 'consent = yes\nrun = 1\n');
  assert.deepEqual(fs.readFileSync(path.join(s.gameDir, 'BepInEx/config/Alpha/76561190000000000/library.bin')), Buffer.alloc(3000, 1));
  assert.ok(!exists(path.join(s.gameDir, 'BepInEx/config/dev.test.beta.cfg')), 'beta was not selected');
  s.engine.mark(journal, 'launched');
  // the mod deletes its library (consent withdrawn) and rewrites its config
  fs.rmSync(path.join(s.gameDir, 'BepInEx/config/Alpha'), { recursive: true });
  h.write(s.gameDir, 'BepInEx/config/dev.test.alpha.cfg', 'consent = no\n');
  s.engine.mark(journal, 'exited');
  s.engine.finish(journal);

  assert.equal(fs.readFileSync(path.join(alphaStore, 'BepInEx/config/dev.test.alpha.cfg'), 'utf8'), 'consent = no\n');
  assert.ok(!exists(path.join(alphaStore, 'BepInEx/config/Alpha')), 'a deleted library must not come back');
  // beta was not part of the session, its data is untouched
  assert.equal(fs.readFileSync(path.join(s.dataDir, 'store/fakegame/beta/data/BepInEx/config/dev.test.beta.cfg'), 'utf8'), 'keys = B\nrun = 1\n');
  assert.deepEqual(h.snapshot(s.gameDir), before);
  h.cleanupDir(s.root);
});

test('crash at every single step: the next start restores the game folder and never loses mod data', async () => {
  // Run the whole flow once to learn every step.
  const probe = h.scene({ foreign: true });
  let j = await probe.engine.prepare(probe.plan, probe.files);
  probe.engine.mark(j, 'launched');
  playGame(probe.gameDir, 1);
  probe.engine.mark(j, 'exited');
  probe.engine.finish(j);
  // second run with data in the store, this is the run we replay
  probe.steps.length = 0;
  j = await probe.engine.prepare(probe.plan, probe.files);
  probe.engine.mark(j, 'launched');
  playGame(probe.gameDir, 2);
  probe.engine.mark(j, 'exited');
  probe.engine.finish(j);
  const total = probe.steps.length;
  const names = [...probe.steps];
  h.cleanupDir(probe.root);
  assert.ok(total > 25, 'expected many crash points, got ' + total);
  for (const must of ['journal', 'moved:BepInEx', 'loader', 'mod:alpha', 'phase:restored', 'saved:alpha', 'store-swap:alpha', 'removed:BepInEx', 'unmoved:BepInEx', 'journal-removed']) {
    assert.ok(names.includes(must), 'missing step ' + must);
  }

  for (let crashAt = 0; crashAt < total; crashAt++) {
    let count = 0;
    let armed = false;
    const s = h.scene({
      foreign: true,
      hook: () => { if (armed && count++ === crashAt) throw new CrashSignal(names[crashAt]); },
    });
    const before = h.snapshot(s.gameDir);

    // session one, undisturbed: puts version 1 into the store
    let journal = await s.engine.prepare(s.plan, s.files);
    s.engine.mark(journal, 'launched');
    playGame(s.gameDir, 1);
    s.engine.mark(journal, 'exited');
    s.engine.finish(journal);
    const storeV1 = storeSnapshot(s);

    // session two dies at step `crashAt`
    armed = true;
    let played = false;
    let crashed = false;
    try {
      journal = await s.engine.prepare(s.plan, s.files);
      s.engine.mark(journal, 'launched');
      playGame(s.gameDir, 2);
      played = true;
      s.engine.mark(journal, 'exited');
      s.engine.finish(journal);
    } catch (e) {
      if (!(e instanceof CrashSignal)) throw e;
      crashed = true;
    }
    assert.ok(crashed, `step ${crashAt} (${names[crashAt]}) did not crash`);

    // the launcher starts again
    const fresh = s.newEngine();
    const pending = fresh.pendingJournals();
    const label = `after a crash at step ${crashAt} (${names[crashAt]})`;
    if (names[crashAt] === 'journal-removed') assert.equal(pending.length, 0, label);
    else assert.equal(pending.length, 1, label + ': journal must survive');
    for (const p of pending) {
      const r = await fresh.recover(p.gameId);
      assert.equal(r.status, 'cleaned', label);
    }

    assert.deepEqual(h.snapshot(s.gameDir), before, label + ': game folder differs');
    assert.equal(fresh.pendingJournals().length, 0, label);
    assert.ok(!exists(path.join(s.gameDir, ASIDE)), label);

    // The store holds version 1 or version 2 completely, never a mix or nothing.
    const store = storeSnapshot(s);
    const strip = (snap) => Object.fromEntries(Object.entries(snap).filter(([k]) => !k.endsWith('meta.json')));
    const lib = 'fakegame/alpha/data/BepInEx/config/Alpha/76561190000000000/library.bin';
    const v1 = sha256(Buffer.alloc(3000, 1));
    const v2 = sha256(Buffer.alloc(3000, 2));
    assert.ok([v1, v2].includes(store[lib]), label + ': library lost');
    if (played) {
      assert.equal(store[lib], v2, label + ': the session had been played, its data must be saved');
      assert.equal(store['fakegame/beta/data/BepInEx/config/dev.test.beta.cfg'], sha256(Buffer.from('keys = B\nrun = 2\n')), label);
    } else {
      assert.deepEqual(strip(store), strip(storeV1), label + ': store changed although the game never ran');
    }
    assert.ok(!Object.keys(store).some((k) => k.includes('data.new') || k.includes('data.old')), label + ': swap leftovers');
    h.cleanupDir(s.root);
  }
});

test('recovery waits while the game is still running', async () => {
  const s = h.scene({ foreign: true });
  const journal = await s.engine.prepare(s.plan, s.files);
  s.engine.mark(journal, 'launched');
  playGame(s.gameDir, 1);
  const during = h.snapshot(s.gameDir);

  s.state.running = true;
  const fresh = s.newEngine();
  const r = await fresh.recover('fakegame');
  assert.equal(r.status, 'running');
  assert.deepEqual(h.snapshot(s.gameDir), during, 'nothing may be touched while the game runs');
  assert.equal(fresh.pendingJournals().length, 1);

  s.state.running = false;
  const r2 = await fresh.recover('fakegame');
  assert.equal(r2.status, 'cleaned');
  assert.deepEqual(r2.saved.map((x) => x.id), ['alpha', 'beta']);
  h.cleanupDir(s.root);
});

