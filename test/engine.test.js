'use strict';

const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('fs');
const path = require('path');
const { CrashSignal, ASIDE } = require('../src/main/engine');
const { writeZip } = require('../src/main/zip');
const { sha256 } = require('../src/main/util');
const h = require('./helpers');

const exists = (p) => fs.existsSync(p);

// What a running game with the mods does to its folder.
function playGame(gameDir, version) {
  h.write(gameDir, 'BepInEx/LogOutput.log', 'log of this session\n');
  h.write(gameDir, 'BepInEx/config/BepInEx.cfg', 'generated by the loader\n');
  h.write(gameDir, 'BepInEx/cache/chainloader_typeloader.dat', 'cache');
  h.write(gameDir, 'BepInEx/config/dev.test.alpha.cfg', `consent = yes\nrun = ${version}\n`);
  h.write(gameDir, 'BepInEx/config/Alpha/76561190000000000/library.bin', Buffer.alloc(3000, version));
  h.write(gameDir, 'BepInEx/config/dev.test.beta.cfg', `keys = B\nrun = ${version}\n`);
}

function storeSnapshot(s) {
  const dir = path.join(s.dataDir, 'store');
  return exists(dir) ? h.snapshot(dir) : {};
}

test('clean install, then removal leaves the game folder exactly as it was', async () => {
  const s = h.scene();
  const before = h.snapshot(s.gameDir);

  const journal = await s.engine.prepare(s.plan, s.files);
  assert.equal(journal.phase, 'restored');
  assert.ok(exists(path.join(s.gameDir, 'BepInEx/core/BepInEx.dll')));
  assert.ok(exists(path.join(s.gameDir, 'winhttp.dll')));
  assert.equal(fs.readFileSync(path.join(s.gameDir, 'BepInEx/plugins/Alpha/Alpha.dll'), 'utf8'), 'alpha code');
  assert.ok(exists(path.join(s.gameDir, 'BepInEx/plugins/Beta/Beta.dll')));
  assert.ok(exists(s.engine.journalFile('fakegame')));

  s.engine.mark(journal, 'launched');
  playGame(s.gameDir, 1);
  s.engine.mark(journal, 'exited');
  const result = s.engine.finish(journal);

  assert.deepEqual(h.snapshot(s.gameDir), before);
  assert.deepEqual(result.leftovers, []);
  assert.ok(!exists(s.engine.journalFile('fakegame')));
  assert.ok(!exists(path.join(s.gameDir, ASIDE)));
  // the loader log is kept for troubleshooting
  assert.equal(fs.readFileSync(path.join(s.dataDir, 'logs/fakegame/LogOutput.log'), 'utf8'), 'log of this session\n');
  h.cleanupDir(s.root);
});

